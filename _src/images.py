"""Image rule: every image on the site must be web-ready.

Runs automatically at the start of every build (build.py calls optimize() then check()).
- New photos: drop a .jpg/.jpeg/.png into assets/img/photos/ or assets/img/events/; it is
  converted to .webp (same name) and the original is removed.
- Anything too large in pixels or bytes is resized / re-encoded to fit its budget.
- Every wide photo gets an 800px "-sm" copy so phones download the small one (srcset).
- Banner photos named hero-* are kept up to 2560px for big screens, plus a 1600px "-md" copy.
- Files already within budget are never touched (no repeated re-compression).
The build fails if any image is still over budget.
"""
import re
from pathlib import Path

from PIL import Image

IMG = Path(__file__).resolve().parent.parent / "assets" / "img"
KB = 1024

# (folder, max long side px, max bytes, lowest webp quality allowed)
PHOTO = (1600, 200 * KB, 58)
PHOTO_SM = (800, 80 * KB, 55)   # long-side cap for the -sm copy
HERO = (2560, 260 * KB, 55)      # files named hero-* (full-width banners; big screens get this)
HERO_MD = (1600, 140 * KB, 55)   # hero-*-md: laptops
EVENT = (1400, 180 * KB, 66)     # flyers have text, keep them sharper
OG_MAX = 150 * KB                # assets/img/og/*.jpg (generated by build.py)
LOGO_HEADER = 30 * KB            # brand/two-stooges-logo.webp, loaded on every page
BRAND_MAX = 300 * KB             # other brand files (schema/OG logo source)


def _budget(p: Path):
    if p.parent.name == "events":
        return EVENT
    if p.stem.endswith("-sm"):
        return PHOTO_SM
    if p.stem.endswith("-md"):
        return HERO_MD
    if p.stem.startswith("hero-"):
        return HERO
    return PHOTO


def _encode(im, out: Path, max_bytes, q_floor, q_start=80):
    """Save as WebP at the highest quality (q_start → q_floor) that fits max_bytes."""
    q = q_start
    while True:
        im.save(out, "WEBP", quality=q, method=6)
        if out.stat().st_size <= max_bytes or q <= q_floor:
            return q
        q -= 4


def _fit(im, long_side):
    w, h = im.size
    s = long_side / max(w, h)
    return im.resize((round(w * s), round(h * s)), Image.LANCZOS) if s < 1 else im


def _open_rgb(p):
    im = Image.open(p)
    return im.convert("RGBA" if im.mode in ("RGBA", "LA") or "transparency" in im.info else "RGB")


def optimize(verbose=True):
    log = []
    for folder in ("photos", "events"):
        d = IMG / folder
        # 1. convert new jpg/png uploads to webp
        for src in sorted(list(d.glob("*.jp*g")) + list(d.glob("*.png")) + list(d.glob("*.JP*G")) + list(d.glob("*.PNG"))):
            out = src.with_suffix(".webp")
            side, mx, qf = _budget(out)
            im = _fit(_open_rgb(src), side)
            q = _encode(im, out, mx, qf)
            src.unlink()
            log.append(f"converted {src.name} → {out.name} ({out.stat().st_size // KB} KB, q{q})")
        # 2. resize / re-encode anything over budget
        for p in sorted(d.glob("*.webp")):
            side, mx, qf = _budget(p)
            with Image.open(p) as im0:
                too_big_px = max(im0.size) > side
                if not too_big_px and p.stat().st_size <= mx * 1.05:
                    continue
                im = _open_rgb(p)
            im = _fit(im, side)
            before = p.stat().st_size // KB
            q = _encode(im, p, mx, qf, q_start=76)
            log.append(f"optimized {folder}/{p.name}: {before} → {p.stat().st_size // KB} KB, {im.size[0]}×{im.size[1]}, q{q}")
        # 3. small copy for phones
        if folder == "photos":
            for p in sorted(d.glob("*.webp")):
                if p.stem.endswith(("-sm", "-md")) or re.search(r"-(\d+|mobile)$", p.stem):
                    continue
                if p.stem.startswith("hero-"):  # banner: laptop copy too
                    md = p.with_name(p.stem + "-md.webp")
                    if not (md.exists() and md.stat().st_mtime >= p.stat().st_mtime):
                        im = _fit(_open_rgb(p), HERO_MD[0])
                        q = _encode(im, md, HERO_MD[1], HERO_MD[2], q_start=76)
                        log.append(f"made {md.name} ({md.stat().st_size // KB} KB, q{q})")
                sm = p.with_name(p.stem + "-sm.webp")
                with Image.open(p) as im0:
                    if im0.size[0] < 1000 or (sm.exists() and sm.stat().st_mtime >= p.stat().st_mtime):
                        continue
                    im = _open_rgb(p)
                im = _fit(im, PHOTO_SM[0])
                q = _encode(im, sm, PHOTO_SM[1], PHOTO_SM[2], q_start=76)
                log.append(f"made {sm.name} ({sm.stat().st_size // KB} KB, q{q})")
    # 4. header/footer logo (every page): 2× its 190px max display width
    logo = IMG / "brand" / "two-stooges-logo.webp"
    if logo.exists() and logo.stat().st_size > LOGO_HEADER:
        with Image.open(logo) as im:
            im = im.convert("RGBA")
            im = im.resize((400, round(im.size[1] * 400 / im.size[0])), Image.LANCZOS)
            before = logo.stat().st_size // KB
            im.save(logo, "WEBP", quality=88, method=6, alpha_quality=90)
            log.append(f"optimized brand/{logo.name}: {before} → {logo.stat().st_size // KB} KB")
    if verbose:
        for line in log:
            print("img:", line)
    return log


def check():
    """Return a list of problems; empty means every image meets the rule."""
    errs = []
    for p in sorted(IMG.rglob("*")):
        if not p.is_file():
            continue
        size = p.stat().st_size
        rel = p.relative_to(IMG)
        top = rel.parts[0]
        if top in ("photos", "events"):
            if p.suffix.lower() != ".webp":
                errs.append(f"{rel}: must be .webp")
                continue
            side, mx, _ = _budget(p)
            with Image.open(p) as im:
                px = max(im.size)
            if size > mx * 1.05:
                errs.append(f"{rel}: {size // KB} KB > {mx // KB} KB")
            if px > side:
                errs.append(f"{rel}: {px}px > {side}px")
        elif top == "og" and size > OG_MAX:
            errs.append(f"{rel}: {size // KB} KB > {OG_MAX // KB} KB")
        elif top == "brand":
            lim = LOGO_HEADER if p.name == "two-stooges-logo.webp" else BRAND_MAX
            if size > lim:
                errs.append(f"{rel}: {size // KB} KB > {lim // KB} KB")
    return errs


if __name__ == "__main__":
    optimize()
    problems = check()
    print("\n".join(problems) or "all images within budget")
